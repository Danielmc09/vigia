"""Generate docs/MAP.md: one line per module with its layer and responsibility (specs/13)."""

import ast
from collections.abc import Iterator
from pathlib import Path

SRC = Path(__file__).parents[1] / "src"
LAYERS = {
    "domain": "domain",
    "signals": "rules",
    "verdict": "rules",
    "policy": "rules",
    "jev": "rules",
    "channel": "adapters",
    "analyst": "adapters",
    "model": "adapters",
    "store": "adapters",
    "services": "application",
    "app": "application",
}


def modules() -> Iterator[tuple[str, Path]]:
    """Yield ``(dotted_name, path)`` for every module under ``src/vigia``, sorted."""
    for path in sorted((SRC / "vigia").rglob("*.py")):
        parts = path.relative_to(SRC).with_suffix("").parts
        if parts[-1] == "__init__":
            parts = parts[:-1]
        yield ".".join(parts), path


def layer(dotted: str) -> str:
    """Architecture layer of a module (specs/09); ``support`` for cross-cutting ones."""
    parts = dotted.split(".")
    return LAYERS.get(parts[1], "support") if len(parts) > 1 else "support"


def render() -> str:
    """Render the full MAP.md content."""
    lines = ["# Module map", "", "Generated by `tools/repo_map.py`; do not edit by hand.", ""]
    for dotted, path in modules():
        doc = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8"))) or ""
        summary = doc.splitlines()[0] if doc else "(no docstring)"
        lines.append(f"- `{dotted}` · {layer(dotted)} · {summary}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    print(render(), end="")
